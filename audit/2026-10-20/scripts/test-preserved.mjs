import fs from 'node:fs/promises';
import path from 'node:path';
import {execFileSync} from 'node:child_process';
import assert from 'node:assert/strict';
import yaml from 'js-yaml';
import {parse} from 'node-html-parser';
import CryptoJS from 'crypto-js';
const root=process.cwd();const site=path.join(root,'.astro/retained');
await fs.mkdir(site,{recursive:true});
for(const folder of ['src','public'])await fs.cp(path.join(root,folder),path.join(site,folder),{recursive:true});
for(const file of ['package.json','astro.config.mjs','svelte.config.js','tsconfig.json','postcss.config.mjs','twilight.config.yaml'])await fs.copyFile(path.join(root,file),path.join(site,file));
const posts=path.join(site,'src/content/posts');
assert.ok(posts.startsWith(path.join(root,'.astro')+path.sep));
await fs.rm(posts,{recursive:true});await fs.mkdir(posts,{recursive:true});
await fs.writeFile(path.join(posts,'visible.md'),'---\ntitle: 保留能力检查\npublished: 2026-01-01\ncomment: true\n---\n\nVisible preservation test.\n');
await fs.writeFile(path.join(posts,'protected.md'),'---\ntitle: Protected preservation test\npublished: 2026-01-01\nencrypted: true\npassword: test-only-password\ncomment: false\ncopyProtection:\n  blockClipboard: true\n---\n\nPRIVATE_PRESERVATION_CONTENT\n');
const config=yaml.load(await fs.readFile(path.join(site,'twilight.config.yaml'),'utf8'));
config.site.generateOgImages=true;config.post.comment.enable=true;
config.post.comment.waline.serverURL='https://comments.example.invalid';
const results={};
for(const provider of ['twikoo','waline']){
 config.post.comment.provider=provider;
 await fs.writeFile(path.join(site,'twilight.config.yaml'),yaml.dump(config));
 execFileSync(process.execPath,[path.join(root,'node_modules/astro/bin/astro.mjs'),'build','--root',site],{stdio:'inherit'});
 const html=parse(await fs.readFile(path.join(site,'dist/posts/visible/index.html'),'utf8'));
 const protectedHtml=parse(await fs.readFile(path.join(site,'dist/posts/protected/index.html'),'utf8'));
 assert.ok(html.querySelector('[data-comment-root]'));
 assert.ok(!protectedHtml.querySelector('[data-comment-root]'));
 assert.match(html.toString(),provider==='twikoo'?/twikoo\.all\.min\.js/:/waline/);
 assert.ok(protectedHtml.querySelector('#password-protection'));
 assert.ok(!protectedHtml.toString().includes('PRIVATE_PRESERVATION_CONTENT'));
 const encrypted=protectedHtml.querySelector('[data-encrypted]').getAttribute('data-encrypted');
 assert.match(CryptoJS.AES.decrypt(encrypted,'test-only-password').toString(CryptoJS.enc.Utf8),/PRIVATE_PRESERVATION_CONTENT/);
 const og=await fs.readFile(path.join(site,'dist/og/visible.png'));
 assert.equal(og.subarray(1,4).toString(),'PNG');
 assert.equal(og.readUInt32BE(16),1200);assert.equal(og.readUInt32BE(20),630);
 results[provider]={commentsRendered:true,perPostDisableRespected:true,passwordDecryptionPassed:true,ogPng:[1200,630]};
}
await fs.writeFile(path.join(root,'.astro/retained-results.json'),JSON.stringify(results,null,2));
console.log('RETAINED_FEATURE_RESULTS',JSON.stringify(results));
